def normalize_lang(lang: str | None) -> str:
    if isinstance(lang, str) and lang in LANGS:
        return lang
    return DEFAULT_UI_LANG


def t(key: str, lang: str | None = None, **kwargs: Any) -> str:
    """Translate ``key`` for ``lang``, falling back to Traditional Chinese."""
    code = normalize_lang(lang)
    table = _TRANSLATIONS.get(code) or _TRANSLATIONS[DEFAULT_UI_LANG]
    text = table.get(key)
    if text is None:
        text = _TRANSLATIONS[DEFAULT_UI_LANG].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def lang_display(code: str) -> str:
    return LANG_DISPLAY.get(code, code)


def lang_from_display(label: str, fallback: str = DEFAULT_UI_LANG) -> str:
    return DISPLAY_TO_LANG.get(label, normalize_lang(fallback))


def format_status(
    message_key: str,
    lang: str | None = None,
    **kwargs: Any,
) -> str:
    """Translate a worker status key, expanding optional verify/warn fragments."""
    data = dict(kwargs)
    if "skip_gone" in data:
        data["verify"] = (
            t("worker.verify_skip_gone", lang=lang) if data.pop("skip_gone") else ""
        )
    if "size_mismatch" in data:
        mismatch = bool(data.pop("size_mismatch"))
        actual = data.pop("actual", "")
        target = data.pop("target", "")
        data["warn"] = (
            t("worker.size_warn", lang=lang, actual=actual, target=target)
            if mismatch
            else ""
        )
    elif "warn" not in data:
        data["warn"] = ""
    if "verify" not in data:
        data["verify"] = ""
    return t(message_key, lang=lang, **data)
